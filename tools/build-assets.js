// Regenerates the bundled assets that let the game run by simply
// double-clicking index.html (browsers block fetch() and fonts on file://).
//
//   node tools/build-assets.js
//
// Run this again whenever you edit a Maps/*/collision.json file or the font.
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const mapsDir = path.join(root, "Maps");

// 1. Collision data -> Maps/collisionData.js
const data = {};
for (const name of fs.readdirSync(mapsDir).sort()) {
  const file = path.join(mapsDir, name, "collision.json");
  if (!fs.existsSync(file)) continue;
  const json = JSON.parse(fs.readFileSync(file, "utf8"));
  data[name] = json.layers[0];
}
fs.writeFileSync(
  path.join(mapsDir, "collisionData.js"),
  "// AUTO-GENERATED by tools/build-assets.js from Maps/*/collision.json - do not edit by hand.\n" +
    "window.collisionData = " + JSON.stringify(data) + ";\n"
);

// 2. Font -> fonts.css (embedded as base64 so it also loads on file://)
const font = fs.readFileSync(path.join(root, "HUD/Font/NormalFont.ttf")).toString("base64");
fs.writeFileSync(
  path.join(root, "fonts.css"),
  "/* AUTO-GENERATED by tools/build-assets.js from HUD/Font/NormalFont.ttf - do not edit by hand. */\n" +
    "@font-face {\n  font-family: 'NormalFont';\n" +
    "  src: url(data:font/ttf;base64," + font + ") format('truetype');\n}\n"
);

console.log("Bundled collision data for: " + Object.keys(data).join(", "));
